#!/usr/bin/env node
/**
 * Zero-dependency client build.
 *
 * The browser bundle cannot import ESM, so inline the pure engine module into
 * the lazy factory. This keeps one source of truth for parsing, span matching,
 * and replacement between Host and Client.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const enginePath = path.join(root, 'lib', 'engine.js');
const sourcePath = path.join(root, 'client.src.js');
const outputPath = path.join(root, 'client.js');

const engineSource = fs.readFileSync(enginePath, 'utf8');
const withoutExport = engineSource.replace(/export\s+default\s+engine\s*;?\s*$/m, 'return engine;');
if (withoutExport === engineSource) {
  throw new Error('build-client: lib/engine.js must end with "export default engine;"');
}

const source = fs.readFileSync(sourcePath, 'utf8');
const marker = '/*@@ENGINE@@*/';
if (!source.includes(marker)) {
  throw new Error(`build-client: ${path.relative(root, sourcePath)} has no ${marker} marker`);
}

const wrapped = `(() => {\n${withoutExport}\n})()`;
const output = `/* Generated by scripts/build-client.mjs from client.src.js + lib/engine.js. Do not edit directly. */\n${source.replace(marker, () => wrapped)}`;

fs.writeFileSync(outputPath, output, 'utf8');
if (output.includes(marker)) throw new Error('build-client: ENGINE marker was not replaced');
console.log(`built ${path.relative(root, outputPath)} (${output.length} bytes)`);
